#!/usr/bin/env bash
# OriginSU on Linux 4.14 (non-GKI): small source compat fixes for OriginSU itself.
# Run from the kernel root after OriginSU's setup.sh (./KernelSU must exist). Idempotent.
set -euo pipefail
[ -d KernelSU/kernel ] || { echo "::error::originsu_compat: KernelSU/kernel missing"; exit 1; }
# Every step below is idempotent.

# 1b) OriginSU non-GKI fix: include preinit.h unconditionally
F=KernelSU/kernel/runtime/ksud_integration.c
if [ -f "$F" ] && grep -q 'ksu_preinit_release' "$F" && \
   ! sed -n '1,/^#if defined(CONFIG_KSU_TRACEPOINT_HOOK)/p' "$F" | grep -q '^#include "preinit/preinit.h"'; then
  sed -i '0,/^#if defined(CONFIG_KSU_TRACEPOINT_HOOK)/s//#include "preinit\/preinit.h" \/\/ fix non-GKI link\n&/' "$F"
fi

# 1c) 4.14 fix: pr_*_ratelimited()/DEFINE_RATELIMIT_STATE need <linux/ratelimit.h>
grep -rlE '_ratelimited\(|DEFINE_RATELIMIT_STATE|__ratelimit\(' \
     --include='*.c' --include='*.h' KernelSU/kernel 2>/dev/null | while read -r f; do
  grep -q 'linux/ratelimit.h' "$f" || { sed -i '1i #include <linux/ratelimit.h> /* fix 4.14 */' "$f"; }
done

# 1d) 4.14 LINK fix: OriginSU calls helpers that don't exist on 4.14 (kvcalloc /
#     kvmalloc_array were added in 4.18, ktime_get_boottime_ns in 5.3). Generate a
#     header with fallbacks for whatever the tree lacks and force-include it into every
#     OriginSU object. Nothing is defined if the tree already has the helper.
has() { grep -rqE "(static[[:space:]]+(__always_)?inline[^;]*[[:space:]*]$1[[:space:]]*\(|^#[[:space:]]*define[[:space:]]+$1\(|extern[^;]*[[:space:]*]$1[[:space:]]*\()" include/linux; }
COMPAT="$PWD/KernelSU/kernel/builder_compat_414.h"
{
  echo '/* Generated by the exynos9820 builder: fallbacks for helpers missing from 4.14 */'
  echo '#ifndef __BUILDER_COMPAT_414_H'
  echo '#define __BUILDER_COMPAT_414_H'
  echo '#if defined(__KERNEL__) && !defined(__ASSEMBLY__)'
  echo '#include <linux/kernel.h>'
  echo '#include <linux/types.h>'
  echo '#include <linux/gfp.h>'
  echo '#include <linux/mm.h>'
  echo '#include <linux/slab.h>'
  echo '#include <linux/vmalloc.h>'
  echo '#include <linux/ktime.h>'
  echo '#include <linux/timekeeping.h>'
  if ! has kvmalloc; then
    echo 'static inline void *kvmalloc(size_t size, gfp_t flags)'
    echo '{ void *p = kmalloc(size, flags | __GFP_NOWARN | __GFP_NORETRY);'
    echo '  return p ? p : __vmalloc(size, flags | __GFP_HIGHMEM, PAGE_KERNEL); }'
  fi
  if ! has kvzalloc; then
    echo 'static inline void *kvzalloc(size_t size, gfp_t flags) { return kvmalloc(size, flags | __GFP_ZERO); }'
  fi
  if ! has kvmalloc_array; then
    echo 'static inline void *kvmalloc_array(size_t n, size_t size, gfp_t flags)'
    echo '{ if (size != 0 && n > SIZE_MAX / size) return NULL; return kvmalloc(n * size, flags); }'
  fi
  if ! has kvcalloc; then
    echo 'static inline void *kvcalloc(size_t n, size_t size, gfp_t flags) { return kvmalloc_array(n, size, flags | __GFP_ZERO); }'
  fi
  if ! has kmemdup_nul; then
    echo 'static inline char *kmemdup_nul(const char *s, size_t len, gfp_t gfp)'
    echo '{ char *b; if (!s) return NULL; b = kmalloc(len + 1, gfp); if (b) { memcpy(b, s, len); b[len] = 0; } return b; }'
  fi
  for c in boottime:boot real:real clocktai:tai; do
    if ! has "ktime_get_${c%%:*}_ns" && has "ktime_get_${c#*:}_ns"; then
      echo "static inline u64 ktime_get_${c%%:*}_ns(void) { return ktime_get_${c#*:}_ns(); }"
    fi
  done
  echo '#endif'
  echo '#endif'
} > "$COMPAT"
grep -q builder_compat_414 KernelSU/kernel/Kbuild || echo "ccflags-y += -include $COMPAT" >> KernelSU/kernel/Kbuild
echo "--- 4.14 compat header ---"; cat "$COMPAT"


# 1e) SuSFS < v2.3 (FreeRunner ships v2.1.0) lacks the per-task "no_su" and "umounted for
#     zygote_next" flags that OriginSU v4.3 calls (susfs_*_current_proc_no_su,
#     susfs_set_current_proc_umounted_for_zygote_next) -> undefined symbols at the final link.
#     Backport them exactly as SuSFS v2.4.0 defines them (TIF bits 34/35, free on arm64 4.14).
D=include/linux/susfs_def.h
if [ -f "$D" ] && ! grep -q 'susfs_is_current_proc_no_su' "$D"; then
  grep -q 'TIF_PROC_UMOUNTED 33' "$D" || { echo "::error::originsu_compat: unexpected $D layout"; exit 1; }
  perl -0pi -e 's{\n(#endif\s*//\s*#ifndef KSU_SUSFS_DEF_H\s*)$}{
/* Backported from SuSFS v2.4.0 for OriginSU (exynos9820 builder) */
#ifndef TIF_PROC_NO_SU
#define TIF_PROC_NO_SU 34
#endif
#ifndef TIF_PROC_UMOUNTED_FOR_ZYGOTE_NEXT
#define TIF_PROC_UMOUNTED_FOR_ZYGOTE_NEXT 35
#endif
static inline void susfs_clear_current_proc_umounted(void) { clear_thread_flag(TIF_PROC_UMOUNTED); }
static inline bool susfs_is_current_proc_umounted_for_zygote_next(void) { return test_thread_flag(TIF_PROC_UMOUNTED_FOR_ZYGOTE_NEXT); }
static inline void susfs_set_current_proc_umounted_for_zygote_next(void) { set_thread_flag(TIF_PROC_UMOUNTED_FOR_ZYGOTE_NEXT); }
static inline void susfs_clear_current_proc_umounted_for_zygote_next(void) { clear_thread_flag(TIF_PROC_UMOUNTED_FOR_ZYGOTE_NEXT); }
static inline bool susfs_is_current_proc_no_su(void) { return test_thread_flag(TIF_PROC_NO_SU); }
static inline void susfs_set_current_proc_no_su(void) { set_thread_flag(TIF_PROC_NO_SU); }
static inline void susfs_clear_current_proc_no_su(void) { clear_thread_flag(TIF_PROC_NO_SU); }

$1}s or die "susfs_def.h: closing #endif not found\n";' "$D"
  grep -q 'susfs_is_current_proc_no_su' "$D" || { echo "::error::originsu_compat: susfs_def.h backport failed"; exit 1; }
  echo "-- susfs_def.h: backported no_su / umounted_for_zygote_next helpers (SuSFS v2.4.0)"
fi
